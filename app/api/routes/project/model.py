from datetime import datetime
from typing import ClassVar, Optional
from uuid import UUID

import uuid6
from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Column,
    Computed,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlmodel import Field, Relationship, SQLModel, func

from app.api.routes.media.model import MediaAsset


class ProjectTagLink(SQLModel, table=True):
    __tablename__: ClassVar[str] = "project_tag_links"

    project_id: UUID = Field(
        sa_column=Column(
            ForeignKey("projects.id", ondelete="CASCADE"), primary_key=True
        )
    )
    tag_id: UUID = Field(
        sa_column=Column(
            ForeignKey("project_tags.id", ondelete="CASCADE"),
            primary_key=True,
            index=True,
        )
    )


class ProjectTag(SQLModel, table=True):
    __tablename__: ClassVar[str] = "project_tags"

    id: UUID = Field(default_factory=uuid6.uuid7, primary_key=True)
    name: str = Field(sa_column=Column(String(50), unique=True, nullable=False))
    created_at: datetime = Field(
        sa_column=Column(
            DateTime(timezone=True), server_default=func.now(), nullable=False
        )
    )


class Project(SQLModel, table=True):
    __tablename__: ClassVar[str] = "projects"
    __table_args__ = (
        CheckConstraint(
            "status IN ('live', 'offline', 'archived')", name="ck_projects_status"
        ),
    )

    id: UUID = Field(default_factory=uuid6.uuid7, primary_key=True)
    name: str = Field(sa_column=Column(String(150), unique=True, nullable=False))
    slug: str = Field(sa_column=Column(String(180), unique=True, nullable=False))
    short_description: str = Field(sa_column=Column(Text, nullable=False))
    long_description: str = Field(sa_column=Column(Text, nullable=False))
    status: str = Field(sa_column=Column(String(16), nullable=False, index=True))
    is_featured: bool = Field(
        default=False,
        sa_column=Column(Boolean, nullable=False, server_default="false"),
    )
    sequence: int = Field(
        default=0, sa_column=Column(Integer, nullable=False, server_default="0")
    )
    github_url: Optional[str] = Field(
        default=None, sa_column=Column(String(500), nullable=True)
    )
    try_url: Optional[str] = Field(
        default=None, sa_column=Column(String(500), nullable=True)
    )
    cover_media_id: Optional[UUID] = Field(
        default=None,
        sa_column=Column(
            ForeignKey("media_assets.id", ondelete="SET NULL"), nullable=True
        ),
    )
    tech_stack: list[str] = Field(
        default_factory=list,
        sa_column=Column(JSONB, nullable=False, server_default=text("'[]'::jsonb")),
    )
    # Generated by Postgres; trigram-indexed for ILIKE search (see 0004).
    search_text: Optional[str] = Field(
        default=None,
        sa_column=Column(
            Text,
            Computed(
                "name || ' ' || short_description || ' ' || (tech_stack)::text",
                persisted=True,
            ),
        ),
    )
    created_at: datetime = Field(
        sa_column=Column(
            DateTime(timezone=True), server_default=func.now(), nullable=False
        )
    )
    updated_at: datetime = Field(
        sa_column=Column(
            DateTime(timezone=True),
            server_default=func.now(),
            onupdate=func.now(),
            nullable=False,
        )
    )

    tags: list[ProjectTag] = Relationship(
        link_model=ProjectTagLink,
        sa_relationship_kwargs={"order_by": "ProjectTag.name", "lazy": "raise"},
    )
    cover: Optional[MediaAsset] = Relationship(
        sa_relationship_kwargs={"lazy": "raise"},
    )


class DataImport(SQLModel, table=True):
    """One row per finished one-off data import (see project_import.py)."""

    __tablename__: ClassVar[str] = "data_imports"

    key: str = Field(sa_column=Column(String(64), primary_key=True))
    done_at: datetime = Field(
        sa_column=Column(
            DateTime(timezone=True), server_default=func.now(), nullable=False
        )
    )
    summary: Optional[dict] = Field(default=None, sa_column=Column(JSONB, nullable=True))
